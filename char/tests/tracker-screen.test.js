import assert from "node:assert/strict";
import { createPreviewAdapter } from "./previews/adapter.js";
import { optionsList, optionRecords, details, resourceCounters, combatOverview, pageForVariant } from "../js/tracker/screen-view.js";

const fighter = createPreviewAdapter("fighter");
assert.equal(pageForVariant("play", "v2.2"), "actions");
assert.equal(pageForVariant("actions", "v2.1"), "play");
assert.equal(pageForVariant("sheet", "v2.1"), "checks");
assert.equal(pageForVariant("checks", "v2.2"), "sheet");
assert.equal(pageForVariant("notes", "v2.1"), "notes");
const overview = combatOverview({ ...fighter.character, portrait:'bad" onerror="alert(1)', swim:20, climb:15, burrow:10, senses:["Blindsight 10 ft"], proficiencies:["Shields"], languages:["Common"] });
for (const text of ["Armor class", "Initiative", "Speed", "Fly", "Swim", "Climb", "Burrow", "Proficiency", "Passive Perception", "Darkvision", "Blindsight", "Shields", "Common"]) assert.ok(overview.includes(text), `Combat exposes ${text}`);
assert.doesNotMatch(overview, /src="bad" onerror=/);
const casterOverview = combatOverview(createPreviewAdapter("caster").character);
assert.match(casterOverview, /Spell attack/); assert.match(casterOverview, /Spell DC/);
const snapshot = JSON.stringify(fighter.character);
fighter.plan("actions:sweep");
assert.equal(JSON.stringify(fighter.character), snapshot, "Planning and cancelling cannot spend");
assert.equal(fighter.confirm("actions:sweep").applied, true);
assert.equal(fighter.character.resources[0].uses.current, 2);
assert.equal(fighter.personal.turn.action, true);
fighter.personal.startTurn();
assert.equal(fighter.character.resources[0].uses.current, 2);
assert.equal(fighter.personal.turn.action, false);
assert.equal(fighter.confirm("actions:second-wind").applied, true);
fighter.personal.toggleTurn("bonus");
assert.equal(fighter.confirm("actions:second-wind").applied, false);
assert.equal(fighter.personal.turn.bonus, false, "Failed spending cannot mark a turn");
assert.equal(fighter.confirm("actions:surge").applied, true);
assert.equal(fighter.personal.turn.action, false, "Free action remains manual");
fighter.adjust("resource", "superiority", -1);
assert.equal(fighter.personal.turn.action, false, "Manual counters do not mark turns");
for (let i = 0; i < 2; i++) assert.equal(fighter.confirm("actions:longsword").applied, true);
assert.equal(fighter.personal.turn.action, true, "Repeated attacks remain available");
assert.equal(createPreviewAdapter("fighter").character.resources[0].uses.current, 3, "Demo sessions stay isolated");

const caster = createPreviewAdapter("caster");
assert.equal(caster.confirm("spells:missile", { optionId: "slot:level-3" }).applied, true);
assert.equal(caster.character.spellcasting.slots[2].current, 0, "Upcasting spends selected slot");
assert.equal(caster.character.spellcasting.slots[0].current, 3);
caster.personal.startTurn();
const slots = JSON.stringify(caster.character.spellcasting.slots);
assert.equal(caster.confirm("spells:detect", { mode: "ritual" }).applied, true);
assert.equal(JSON.stringify(caster.character.spellcasting.slots), slots);
assert.equal(caster.personal.turn.action, false);
assert.equal(caster.confirm("spells:web").applied, true);
assert.equal(caster.character.concentration.name, "Web");
assert.equal(caster.confirm("inventory:wand").applied, true);
assert.equal(caster.character.inventory.find((item) => item.id === "wand").charges.current, 1);
assert.equal(caster.plan("inventory:potion").canConfirm, false, "No inferred potion automation");
caster.hp("damage", 6);
assert.deepEqual(caster.character.hp, { current: 22, max: 32, temp: 0 });
caster.rest("long");
assert.equal(caster.character.spellcasting.slots[2].current, 2);
assert.equal(caster.character.hp.current, 32);
assert.equal(caster.character.inventory.find((item) => item.id === "wand").charges.current, 3);

fighter.personal.togglePin("resources:superiority");
assert.equal(optionRecords(fighter, "play", "", "").some((item) => item.key === "resources:superiority"), true);
const rows = optionsList(fighter, { page: "play", query: "", timing: "" });
assert.equal((rows.match(/data-record="actions:longsword"/g) || []).length, 1, "Pins do not duplicate options");
assert.equal(optionRecords(fighter, "play", "second wind", "bonus").length, 1);
assert.match(optionsList(fighter, { page: "play", query: "missing", timing: "" }), /No matching options/);
fighter.character.actions[0].name = '<img src=x onerror="alert(1)">';
assert.doesNotMatch(details(fighter.record("actions:longsword"), fighter), /<img/);
fighter.character.resources[0].uses.current = '<img src=x onerror="alert(1)">';
assert.doesNotMatch(resourceCounters(fighter), /<img/, "Imported resource values are escaped at the presentation boundary");

const reader = createPreviewAdapter("npc", true);
const before = JSON.stringify(reader.character);
assert.doesNotMatch(before, /lost heir|signet|DM notes/);
assert.equal(reader.confirm("actions:breath").applied, false);
reader.hp("damage", 5); reader.adjust("resource", "breath", -1); reader.rest("long");
reader.addNote("Secret", "No"); reader.addCondition("No"); reader.setPrepared("none", true);
reader.toggleFlag("inspiration"); reader.toggleTracker("none", true); reader.toggleDeathSave("successes", 0);
reader.personal.toggleTurn("action"); reader.personal.startTurn();
assert.equal(JSON.stringify(reader.character), before, "Read-only commands cannot change the fixture");
assert.deepEqual(reader.personal.turn, { action: false, bonus: false, reaction: false });
const pin = reader.personal.pins.has("actions:breath"); reader.personal.togglePin("actions:breath");
assert.notEqual(reader.personal.pins.has("actions:breath"), pin, "Read-only viewers may keep personal pins");
console.log("Tracker 2.x preview checks passed: domain reuse, cancellation, slots/upcasting, concentration, pins, isolation, permissions, and escaping.");
